_ARXIV_BARE_RE = re.compile(r'(\d{4}\.\d{4,5}|[a-z-]+/\d{7})', re.IGNORECASE)
_ARXIV_ABS_RE = re.compile(r'/abs/([^/?#]+)')
_PROVIDER_COMMENT_RE = re.compile(r'^\s*<!--\s*provider:\s*([^->\n]+?)\s*-->\s*')
_PROVIDER_PILL_RE = re.compile(r'Generated by ([^<]+)</span>|生成模型：([^<|]+)')
_CODE_FENCE_RE = re.compile(r'```(?:html)?', re.IGNORECASE)
_PAPER_TAGS_BLOCK_RE = re.compile(r'\s*<div class="paper-tags">.*?</div>', re.DOTALL)
_DATA_TOPICS_ATTR_RE = re.compile(r'\s+data-topics="[^"]*"')
_INDEX_BOX_RE = re.compile(r'<div class="index-box">(.*?)</div>', re.DOTALL)
_HIGHLIGHT_BOX_RE = re.compile(r'<div class="highlight-box">(.*?)</div>', re.DOTALL)
_PAPER_ITEM_START_RE = re.compile(r'<div class="paper-item"[^>]*id="p(\d+)"[^>]*>')
_DIV_TOKEN_RE = re.compile(r'<div\b[^>]*>|</div>', re.IGNORECASE)
_H3_RE = re.compile(r'<h3>(.*?)</h3>', re.DOTALL)
_H3_LINK_RE = re.compile(r'<a[^>]*href="([^"]*)"[^>]*>(.*?)</a>', re.DOTALL)
_STATUS_SPAN_RE = re.compile(r'<span class="status-tag status-([a-z]+)">(.*?)</span>', re.DOTALL)
_METHOD_SPAN_RE = re.compile(r'<span class="method-tag">\s*\[?([A-Za-z]+)\]?\s*</span>')
_FIELD_P_RE = re.compile(r'<p(?:\s+[^>]*)?>\s*<strong>([^<]+)</strong>(.*?)</p>', re.DOTALL)
_HTML_TAG_RE = re.compile(r'<[^>]+>')
_CJK_RE = re.compile(r'[\u4e00-\u9fff]')
_HIGHLIGHT_P_ATTR_RE = re.compile(r'<p(\s+[^>]*)?>(.*?)</p>', re.DOTALL)
_WS_RE = re.compile(r'\s+')


def bare_arxiv_id(raw: str) -> str:
    """Return the versionless arXiv identifier from a URL or ID string.

    Args:
        raw: arXiv URL, ``arXiv:...`` string, or versioned identifier.

    Returns:
        Normalized identifier such as ``2605.13799``, or empty string if absent.
    """
    match = _ARXIV_BARE_RE.search(raw or '')
    return match.group(1) if match else ''


def display_arxiv_id(raw: str) -> str:
    """Return the display arXiv ID (preserving version suffix if present)."""
    m = _ARXIV_ABS_RE.search(raw or '')
    if m:
        return m.group(1).strip()
    cleaned = re.sub(r'^arXiv:', '', (raw or '').strip(), flags=re.IGNORECASE)
    return cleaned


def _clean_text(raw_html: str) -> str:
    text = _HTML_TAG_RE.sub('', raw_html or '')
    return _WS_RE.sub(' ', _html_unescape(text)).strip()


def _detect_hl_lang(attrs: str, body: str) -> str:
    attrs_l = (attrs or '').lower()
    if 'data-lang="en"' in attrs_l or "data-lang='en'" in attrs_l or 'hl-en' in attrs_l:
        return 'en'
    if 'data-lang="zh"' in attrs_l or "data-lang='zh'" in attrs_l or 'hl-zh' in attrs_l:
        return 'zh'
    return 'zh' if _CJK_RE.search(_clean_text(body)) else 'en'


def strip_paper_tags(fragment_html: str) -> str:
    """Remove render-time topic/object badges so fragments stay pure LLM output."""
    cleaned = _PAPER_TAGS_BLOCK_RE.sub('', fragment_html or '')
    return _DATA_TOPICS_ATTR_RE.sub('', cleaned)


def iter_paper_item_spans(html: str) -> list[tuple[int, int, int]]:
    """Locate balanced ``(number, start_idx, end_idx)`` spans for paper cards.

    Args:
        html: Fragment or report HTML containing ``.paper-item`` divs.

    Returns:
        Ordered list of ``(paper_number, start_offset, end_offset)`` tuples.
    """
    spans: list[tuple[int, int, int]] = []
    pos = 0
    while True:
        m = _PAPER_ITEM_START_RE.search(html, pos)
        if not m:
            break
        num = int(m.group(1))
        start = m.start()
        depth = 0
        end = -1
        for tok in _DIV_TOKEN_RE.finditer(html, start):
            if tok.group(0).startswith('</'):
                depth -= 1
                if depth == 0:
                    end = tok.end()
                    break
            else:
                depth += 1
        if end == -1:
            break
        spans.append((num, start, end))
        pos = end
    return spans


def extract_fragment_from_report_html(full_html: str) -> tuple[str, str]:
    """Extract the clean body fragment and provider name from a full daily report.

    Args:
        full_html: Complete standalone daily report HTML document.

    Returns:
        Tuple of ``(fragment_html, provider_name)``.

    Raises:
        ValueError: If no report body markers exist in ``full_html``.
    """
    m_prov = _PROVIDER_PILL_RE.search(full_html)
    provider = 'unknown'
    if m_prov:
        provider = (m_prov.group(1) or m_prov.group(2) or 'unknown').strip()

    starts = [
        idx
        for marker in (
            '<div class="index-box"',
            '<div class="highlight-box"',
            '<div class="paper-item"',
        )
        if (idx := full_html.find(marker)) != -1
    ]
    if not starts:
        raise ValueError('No report body markers found in HTML')
    start = min(starts)
    script_idx = full_html.find('<script>', start)
    chunk = full_html[start : (script_idx if script_idx != -1 else len(full_html))].rstrip()
    if chunk.endswith('</div>'):
        # Strip the single closing tag belonging to <div class="container">.
        cand = chunk[:-6].rstrip()
        if cand.endswith('</div>'):
            chunk = cand
    return strip_paper_tags(chunk), provider


def save_fragment(date_str: str, fragment_html: str, provider: str, reports_dir: str) -> str:
    """Persist a clean body fragment under ``<reports_dir>/fragments/<date>.html``.

    Args:
        date_str: Report date formatted as ``YYYY-MM-DD``.
        fragment_html: Clean body HTML without standalone page chrome.
        provider: Provider slug recorded in a leading HTML comment.
        reports_dir: Root reports directory.

    Returns:
        Path of the written fragment file.
    """
    frag_dir = os.path.join(reports_dir, 'fragments')
    os.makedirs(frag_dir, exist_ok=True)
    path = os.path.join(frag_dir, f'{date_str}.html')
    clean_body = strip_paper_tags(fragment_html).strip()
    content = f'<!-- provider: {provider} -->\n{clean_body}\n'
    tmp_path = f'{path}.tmp'
    with open(tmp_path, 'w', encoding='utf-8') as f:
        f.write(content)
    os.replace(tmp_path, path)
    return path


def load_fragment(date_str: str, reports_dir: str) -> tuple[str, str] | None:
    """Read a saved body fragment and its recorded provider slug if present.

    Args:
        date_str: Report date formatted as ``YYYY-MM-DD``.
        reports_dir: Root reports directory.

    Returns:
        Tuple ``(fragment_html, provider)``, or ``None`` if the file is absent.
    """
    path = os.path.join(reports_dir, 'fragments', f'{date_str}.html')
    if not os.path.exists(path):
        return None
    with open(path, encoding='utf-8-sig') as f:
        raw = f.read()
    provider = 'unknown'
    m = _PROVIDER_COMMENT_RE.match(raw)
    if m:
        provider = m.group(1).strip() or 'unknown'
        raw = raw[m.end() :]
    return strip_paper_tags(raw.strip()), provider


def _fallback_card(number: int, paper: dict) -> str:
    url = str(paper.get('url') or '').strip()
    disp_id = display_arxiv_id(url) or str(number)
    status_class, label = classify_pub_status(
        str(paper.get('comment') or ''),
        str(paper.get('journal_ref') or ''),
        str(paper.get('doi') or ''),
    )
    badge = ''
    if status_class != 'preprint':
        badge = f' <span class="status-tag status-{status_class}">{_html_escape(label)}</span>'
    title = _html_escape(str(paper.get('title') or ''))
    authors = _html_escape(str(paper.get('authors') or 'Unknown'))
    abstract = _html_escape(str(paper.get('summary') or ''))
    return (
        f'<div class="paper-item" id="p{number}">\n'
        f'<h3>[{number}] <a href="{_html_escape(url)}">{_html_escape(disp_id)}</a>{badge}</h3>\n'
        f'<p><strong>英文标题：</strong>{title}</p>\n'
        f'<p><strong>作者：</strong>{authors}</p>\n'
        '<details class="fallback-abstract">'
        '<summary>Abstract (auto-completed fallback entry)</summary>'
        f'<p>{abstract}</p>'
        '</details>\n'
        '</div>'
    )


def finalize_fragment(
    raw_report: str,
    papers: list[dict],
    normalize_fn: Callable[[str], str],
) -> tuple[str, list[str]]:
    """Sanitize raw LLM HTML output and append fallbacks for any omitted papers.

    Args:
        raw_report: Raw text returned by the LLM provider.
        papers: Original ordered list of fetched paper dicts.
        normalize_fn: Normalization callable such as ``normalize_method_tags``.

    Returns:
        Tuple of ``(cleaned_fragment_html, warning_messages)``.
    """
    warnings: list[str] = []
    text = _CODE_FENCE_RE.sub('', raw_report or '').strip()
    first_tag = text.find('<')
    last_div = text.rfind('</div>')
    if first_tag > 0:
        text = text[first_tag:]
    if last_div != -1 and last_div + 6 < len(text):
        text = text[: last_div + 6]
    text = strip_paper_tags(normalize_fn(text)).strip()

    if papers and '<div class="index-box">' not in text:
        warnings.append('Report fragment is missing <div class="index-box">.')

    present_nums = {num for num, _, _ in iter_paper_item_spans(text)}
    missing_nums = [idx for idx in range(1, len(papers) + 1) if idx not in present_nums]
    if missing_nums:
        warnings.append(f'LLM omitted {len(missing_nums)} paper item(s): {missing_nums}')
        fallback_cards = [_fallback_card(idx, papers[idx - 1]) for idx in missing_nums]
        text = (text + '\n\n' + '\n\n'.join(fallback_cards)).strip()

        m_idx = _INDEX_BOX_RE.search(text)
        if m_idx:
            idx_body = m_idx.group(1)
            unindexed = [idx for idx in missing_nums if f'#p{idx}' not in idx_body]
            if unindexed:
                links = ', '.join(f'<a href="#p{idx}">[{idx}]</a>' for idx in unindexed)
                extra_line = f'<p><strong>Auto-completed:</strong> {links}</p>'
                new_box = f'<div class="index-box">{idx_body.rstrip()}\n{extra_line}\n</div>'
                text = text[: m_idx.start()] + new_box + text[m_idx.end() :]

    return text, warnings


def parse_fragment(fragment_html: str) -> dict:
    """Parse topics, highlights, and per-paper bilingual fields from a fragment.

    Args:
        fragment_html: Clean body HTML fragment for one daily report.

    Returns:
        Dict with ``topics_by_num``, ``slugs_by_num``, ``highlights_by_num``,
        and ``items`` (mapping paper number ``1..N`` to field dicts).
    """
    topics_by_num: dict[int, list[str]] = {}
    slugs_by_num: dict[int, list[str]] = {}
    m_idx = _INDEX_BOX_RE.search(fragment_html)
    if m_idx:
        for line in re.findall(r'<p(?:\s+[^>]*)?>(.*?)</p>', m_idx.group(1), re.DOTALL):
            m_lbl = re.search(r'<strong>([^<]+)</strong>', line)
            if not m_lbl:
                continue
            raw_label = m_lbl.group(1).strip().rstrip('：:').strip()
            spec = resolve_topic(raw_label)
            canonical_label = spec.label if spec else raw_label
            for num_s in re.findall(r'href="#p(\d+)"', line):
                num = int(num_s)
                topics_by_num.setdefault(num, [])
                if canonical_label not in topics_by_num[num]:
                    topics_by_num[num].append(canonical_label)
                if spec:
                    slugs_by_num.setdefault(num, [])
                    if spec.slug not in slugs_by_num[num]:
                        slugs_by_num[num].append(spec.slug)

    highlights_zh_by_num: dict[int, str] = {}
    highlights_en_by_num: dict[int, str] = {}
    m_hl = _HIGHLIGHT_BOX_RE.search(fragment_html)
    if m_hl:
        for attrs, line in _HIGHLIGHT_P_ATTR_RE.findall(m_hl.group(1)):
            m_num = re.search(r'href="#p(\d+)"', line)
            if not m_num:
                continue
            num = int(m_num.group(1))
            stripped = _clean_text(re.sub(r'<a[^>]*>.*?</a>', '', line, count=1, flags=re.DOTALL))
            if not stripped:
                continue
            lang = _detect_hl_lang(attrs, stripped)
            if lang == 'en':
                highlights_en_by_num[num] = stripped
            else:
                highlights_zh_by_num[num] = stripped
    highlights_by_num: dict[int, str] = {
        n: highlights_zh_by_num.get(n) or highlights_en_by_num.get(n, '')
        for n in sorted(set(highlights_zh_by_num) | set(highlights_en_by_num))
    }

    items: dict[int, dict] = {}
    for num, start, end in iter_paper_item_spans(fragment_html):
        card = fragment_html[start:end]
        url = ''
        arxiv_disp = ''
        status = 'submitted'
        status_label = ''

        m_h3 = _H3_RE.search(card)
        if m_h3:
            h3_html = m_h3.group(1)
            m_link = _H3_LINK_RE.search(h3_html)
            if m_link:
                url = _html_unescape(m_link.group(1)).strip()
                arxiv_disp = _clean_text(m_link.group(2))
            m_stat = _STATUS_SPAN_RE.search(h3_html)
            if m_stat:
                status = m_stat.group(1).strip().lower()
                status_label = normalize_status_label(_clean_text(m_stat.group(2)))

        fields: dict[str, str] = {}
        method_tag = ''
        for raw_key, raw_val in _FIELD_P_RE.findall(card):
            key = _html_unescape(raw_key).strip().rstrip('：:').strip()
            if key == '研究方法':
                m_tag = _METHOD_SPAN_RE.search(raw_val)
                if m_tag:
                    method_tag = m_tag.group(1).strip()
                    val_no_tag = _METHOD_SPAN_RE.sub('', raw_val, count=1)
                    fields[key] = _clean_text(val_no_tag)
                else:
                    cleaned_val = _clean_text(raw_val)
                    m_lead = re.match(r'^\[([A-Za-z]+)\]\s*(.*)$', cleaned_val)
                    if m_lead:
                        method_tag = m_lead.group(1)
                        fields[key] = m_lead.group(2).strip()
                    else:
                        fields[key] = cleaned_val
            else:
                fields[key] = _clean_text(raw_val)

        pid = bare_arxiv_id(arxiv_disp) or bare_arxiv_id(url)
        items[num] = {
            'number': num,
            'pid': pid,
            'arxiv_id': arxiv_disp or pid,
            'url': url,
            'status': status,
            'status_label': status_label,
            'title_en': fields.get('英文标题', ''),
            'title_zh': fields.get('中文标题', ''),
            'authors': fields.get('作者', ''),
            'question_zh': fields.get('研究问题', ''),
            'question_en': fields.get('Research Question', ''),
            'method_zh': fields.get('研究方法', ''),
            'method_en': fields.get('Method', ''),
            'method_tag': method_tag,
            'result_zh': fields.get('研究结果', ''),
            'result_en': fields.get('Results', ''),
            'caveat_zh': fields.get('潜在不足与延伸方向', ''),
            'caveat_en': (
                fields.get('Limitations & Next Steps', '')
                or fields.get('Limitations and Next Steps', '')
            ),
            'topics': topics_by_num.get(num, []),
            'topic_slugs': slugs_by_num.get(num, []),
            'is_highlight': 1 if num in highlights_by_num else 0,
            'highlight_zh': highlights_by_num.get(num, ''),
            'highlight_en': highlights_en_by_num.get(num, ''),
        }

    return {
        'topics_by_num': topics_by_num,
        'slugs_by_num': slugs_by_num,
        'highlights_by_num': highlights_by_num,
        'highlights_en_by_num': highlights_en_by_num,
        'items': items,
    }


_INDEX_PARAGRAPH_RE = re.compile(r'<p(?:\s+[^>]*)?>\s*<strong>(.*?)</strong>(.*?)</p>', re.DOTALL)
_LEADING_ANCHOR_RE = re.compile(r'^\s*<a[^>]*href="#p\d+"[^>]*>.*?</a>\s*', re.DOTALL)
_TIER_BREAKTHROUGH_RE = re.compile(
    r'\b(first|discover\w*|detect\w*|upper\s+limit|challeng\w*|tension|rul\w*\s+out|reject\w*|'
    r'novel|breakthrough|mile-?stone|resolv\w*|constraint\w*)\b|首次|发现|挑战|推翻|上限',
    re.IGNORECASE,
)
_TIER_QUANT_RE = re.compile(
    r'(?:\d+(?:\.\d+)?\s*(?:%|σ|sigma|TeV|PeV|EeV|MeV|GeV|kpc|Mpc|Gpc|Hz)|\d+\s*σ)',
    re.IGNORECASE,
)
_TIER_MISSION_RE = re.compile(
    r'\b(JWST|Einstein\s+Probe|EP-?WXT|EP-?FXT|LIGO|Virgo|KAGRA|IceCube|LHAASO|'
    r'Fermi|Chandra|IXPE|NuSTAR|XMM-?Newton|Swift|ALMA|EHT|CTA|SVOM|NICER)\b',
    re.IGNORECASE,
)


def format_index_box(nums_by_slug: dict[str, list[int]]) -> str:
    """Format canonical ordered ``<div class="index-box">`` HTML from slug -> paper numbers."""
    lines = ['<div class="index-box">', '<h3>领域索引</h3>']
    for spec in TOPICS:
        nums = sorted(
            dict.fromkeys(int(n) for n in (nums_by_slug.get(spec.slug) or []) if int(n) > 0)
        )
        if not nums:
            continue
        links = ', '.join(f'<a href="#p{n}">[{n}]</a>' for n in nums)
        lines.append(f'<p><strong>{_html_escape(spec.label)}：</strong> {links}</p>')
    lines.append('</div>')
    return '\n'.join(lines)


def _extract_raw_index_labels(fragment_html: str) -> dict[int, list[str]]:
    """Extract ordered raw topic labels per paper number from ``.index-box``."""
    out: dict[int, list[str]] = {}
    m_idx = _INDEX_BOX_RE.search(fragment_html)
    if not m_idx:
        return out
    for m_p in _INDEX_PARAGRAPH_RE.finditer(m_idx.group(1)):
        raw_label = _clean_text(m_p.group(1)).rstrip('：: ')
        if not raw_label:
            continue
        for num_s in re.findall(r'#p(\d+)', m_p.group(2)):
            num = int(num_s)
            labels = out.setdefault(num, [])
            if raw_label not in labels:
                labels.append(raw_label)
    return out


def _remap_card_numbers(card_html: str, old_num: int, new_num: int) -> str:
    """Shift paper anchors and visible heading index inside a single ``.paper-item``."""
    if old_num == new_num:
        return card_html
    updated = re.sub(rf'id="p{old_num}"', f'id="p{new_num}"', card_html, count=1)
    updated = re.sub(rf'href="#p{old_num}"', f'href="#p{new_num}"', updated)
    updated = re.sub(
        rf'(<h3\b[^>]*>.*?<a[^>]*>)\s*\[{old_num}\]\s*(</a>)',
        rf'\g<1>[{new_num}]\g<2>',
        updated,
        count=1,
        flags=re.DOTALL,
    )
    return updated


def _score_highlight(highlight_html: str) -> int:
    """Score a highlight sentence deterministically for multi-chunk selection."""
    text = _clean_text(highlight_html)
    score = 0
    if _TIER_BREAKTHROUGH_RE.search(text):
        score += 100
    score += 15 * len(_TIER_QUANT_RE.findall(text))
    score += 10 * len(_TIER_MISSION_RE.findall(text))
    score += min(len(text), 200) // 40
    return score


def merge_chunk_fragments(
    chunk_outputs: list[tuple[int, int, str]],
    max_highlights: int = 3,
) -> str:
    """Combine chunked LLM HTML fragments into one ordered report body.

    Args:
        chunk_outputs: Sequence of ``(start_index, count, raw_chunk_html)`` tuples,
            where ``start_index`` is the 1-based global index of the first paper
            in that chunk.
        max_highlights: Maximum number of highlights to retain after deduplication.

    Returns:
        Combined HTML body containing a merged ``.index-box``, optional capped
        ``.highlight-box``, and ordered ``#p1..#pN`` cards.
    """
    paper_slugs: dict[int, list[str]] = {}
    highlights: dict[int, dict[str, str]] = {}
    cards: dict[int, str] = {}

    for start_index, count, raw_chunk in chunk_outputs:
        cleaned = _CODE_FENCE_RE.sub('', raw_chunk).strip()
        cleaned = strip_paper_tags(cleaned)
        spans = iter_paper_item_spans(cleaned)

        delta = 0
        if start_index > 1:
            raw_nums = [n for n, _, _ in spans]
            if not raw_nums:
                raw_nums = list(_extract_raw_index_labels(cleaned).keys())
            if raw_nums and all(1 <= n <= count for n in raw_nums):
                delta = start_index - 1

        for raw_num, labels in _extract_raw_index_labels(cleaned).items():
            num = raw_num + delta
            bucket = paper_slugs.setdefault(num, [])
            for raw_label in labels:
                spec = resolve_topic(raw_label)
                if spec is None:
                    key = classify_legacy_key(raw_label)
                    spec = TOPIC_BY_SLUG.get(key)
                if spec and spec.slug not in bucket and len(bucket) < 2:
                    bucket.append(spec.slug)

        m_hl = _HIGHLIGHT_BOX_RE.search(cleaned)
        if m_hl:
            for m_p in _HIGHLIGHT_P_ATTR_RE.finditer(m_hl.group(1)):
                attrs = m_p.group(1) or ''
                p_inner = m_p.group(2).strip()
                m_href = re.search(r'href="#p(\d+)"', p_inner)
                if not m_href:
                    continue
                num = int(m_href.group(1)) + delta
                body_html = _LEADING_ANCHOR_RE.sub('', p_inner).strip()
                if not body_html:
                    continue
                lang = _detect_hl_lang(attrs, body_html)
                bucket = highlights.setdefault(num, {})
                if lang not in bucket or len(body_html) > len(bucket[lang]):
                    bucket[lang] = body_html

        for raw_num, start_pos, end_pos in spans:
            actual_num = raw_num + delta
            card_html = cleaned[start_pos:end_pos]
            if delta:
                card_html = _remap_card_numbers(card_html, raw_num, actual_num)
            cards.setdefault(actual_num, card_html)

    nums_by_slug: dict[str, list[int]] = {}
    for num in sorted(paper_slugs):
        for slug in paper_slugs[num]:
            nums_by_slug.setdefault(slug, []).append(num)

    sections = [format_index_box(nums_by_slug)]

    if highlights:
        selected_nums = sorted(highlights)
        if max_highlights > 0 and len(selected_nums) > max_highlights:
            ranked = sorted(
                selected_nums,
                key=lambda n: (-max(_score_highlight(v) for v in highlights[n].values()), n),
            )
            selected_nums = sorted(ranked[:max_highlights])
        hl_lines = ['<div class="highlight-box">', '<h3>今日重点</h3>']
        for n in selected_nums:
            entry = highlights[n]
            if entry.get('zh'):
                hl_lines.append(
                    f'<p class="hl-zh" data-lang="zh"><a href="#p{n}">[{n}]</a> {entry["zh"]}</p>'
                )
            if entry.get('en'):
                hl_lines.append(
                    f'<p class="hl-en" data-lang="en"><a href="#p{n}">[{n}]</a> {entry["en"]}</p>'
                )
        hl_lines.append('</div>')
        sections.append('\n'.join(hl_lines))

    for n in sorted(cards):
        sections.append(cards[n])

    return '\n\n'.join(sections)


def migrate_fragment_topics(
    fragment_html: str,
    paper_meta_by_pid: dict[str, dict] | None = None,
) -> str:
    """Reclassify legacy topic labels inside a fragment into 16 canonical slugs.

    Parses raw ``.index-box`` headings before canonical collapse so legacy buckets
    such as ``SNe/TDE``, ``BH/Jet``, and ``Theory/Inst`` can be accurately split
    via :func:`core.topics.reclassify_paper_topics`.
    """
    cleaned = strip_paper_tags(fragment_html)
    raw_labels_by_num = _extract_raw_index_labels(cleaned)
    parsed = parse_fragment(cleaned)
    items = parsed['items']

    nums_by_slug: dict[str, list[int]] = {}
    all_nums = sorted(set(items.keys()) | set(raw_labels_by_num.keys()))
    for num in all_nums:
        item = items.get(num, {})
        pid = item.get('pid', '')
        meta = (paper_meta_by_pid or {}).get(pid, {})
        raw_keys: list[str] = []
        for raw_label in raw_labels_by_num.get(num, []):
            key = classify_legacy_key(raw_label)
            if key and key not in raw_keys:
                raw_keys.append(key)
        if not raw_keys:
            raw_keys = list(item.get('topics') or [])

        title = item.get('title_en') or meta.get('title', '')
        summary = meta.get('summary') or ' '.join(
            s
            for s in (
                item.get('question_en', ''),
                item.get('method_en', ''),
                item.get('result_en', ''),
                item.get('caveat_en', ''),
            )
            if s
        )
        zh_text = ' '.join(
            s
            for s in (
                item.get('title_zh', ''),
                item.get('question_zh', ''),
                item.get('method_zh', ''),
                item.get('result_zh', ''),
                item.get('caveat_zh', ''),
            )
            if s
        )
        slugs = reclassify_paper_topics(
            raw_topics=raw_keys,
            title=title,
            summary=summary,
            categories=meta.get('categories', ''),
            method_tag=item.get('method_tag', ''),
            zh_text=zh_text,
        )
        for slug in slugs:
            nums_by_slug.setdefault(slug, []).append(num)

    new_index_box = format_index_box(nums_by_slug)
    if _INDEX_BOX_RE.search(cleaned):
        return _INDEX_BOX_RE.sub(lambda _m: new_index_box, cleaned, count=1)
    return new_index_box + '\n\n' + cleaned
